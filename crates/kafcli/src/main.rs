/// Stack size for the thread that runs kafcli. apache-avro lets one datum nest up to 256 decoder
/// levels (kafcli's 64 JSON levels need about three apache levels each), which needs about 8 to 12 MiB
/// in a debug build. The main thread has 8 MiB on Linux and 1 MiB on Windows, so the work runs on a
/// thread with this much stack instead of on the main thread.
const CLI_THREAD_STACK_BYTES: usize = 64 * 1024 * 1024;

fn main() -> ExitCode {
    let worker = std::thread::Builder::new()
        .name("kafcli-main".into())
        .stack_size(CLI_THREAD_STACK_BYTES)
        .spawn(run_cli);
    let worker = match worker {
        Ok(worker) => worker,
        Err(error) => {
            write_error_line(&format!("error: could not start kafcli thread: {error}"));
            return ExitCode::from(KafcliExitCode::Failure as u8);
        }
    };
    match worker.join() {
        Ok(exit_code) => exit_code,
        Err(_) => {
            write_error_line("error: kafcli thread panicked");
            ExitCode::from(KafcliExitCode::Failure as u8)
        }
    }
}

fn run_cli() -> ExitCode {
    let arguments = match CommandLineArguments::try_parse() {
        Ok(arguments) => arguments,
        Err(usage_error) => return report_usage_error(&usage_error),
    };
    logging::initialize_logging(arguments.global.verbosity);
    let resolver = CompositeSecretResolver::with_default_sources();
    match run(arguments, &resolver) {
        Ok(output) => write_command_output(output),
        Err(error) => {
            write_error_line(&format!("error: {error:#}"));
            resolve_exit_code(&error)
        }
    }
}

/// Prints the command's text first, then its trailing error, so a partly failed run keeps its report on stdout.
fn write_command_output(output: RenderedOutput) -> ExitCode {
    let stdout_exit_code = match &output.text {
        Some(text) => write_result_to_stdout(text),
        None => ExitCode::from(KafcliExitCode::Success as u8),
    };
    match output.trailing_error {
        Some(error) => {
            write_error_line(&format!("error: {error:#}"));
            resolve_exit_code(&error)
        }
        None => stdout_exit_code,
    }
}

/// Help and version are normal output; any other usage error (unknown command, bad value) is a
/// failure. Exit code 2 is reserved for limits, so clap's own code 2 is never used.
fn report_usage_error(usage_error: &clap::Error) -> ExitCode {
    match usage_error.kind() {
        ErrorKind::DisplayHelp | ErrorKind::DisplayVersion => {
            let _ = usage_error.print();
            ExitCode::from(KafcliExitCode::Success as u8)
        }
        _ => {
            // Clap's text is generated by this program, not supplied by the broker or the user,
            // so it is printed as clap formats it (multi-line) without terminal sanitization.
            let _ = usage_error.print();
            ExitCode::from(KafcliExitCode::Failure as u8)
        }
    }
}

/// Writes one line to stderr without panicking when stderr is closed; the text is sanitized
/// because it may contain values typed by the user or sent by the broker.
fn write_error_line(text: &str) {
    let _ = writeln!(io::stderr().lock(), "{}", sanitize_for_terminal(text));
}

/// A reader that closes the pipe early (for example `kafcli ... | head`) is a normal end, not a failure.
fn write_result_to_stdout(rendered: &str) -> ExitCode {
    match writeln!(io::stdout().lock(), "{rendered}") {
        Ok(()) => ExitCode::from(KafcliExitCode::Success as u8),
        Err(error) if error.kind() == IoErrorKind::BrokenPipe => {
            ExitCode::from(KafcliExitCode::Success as u8)
        }
        Err(error) => {
            write_error_line(&format!("error: {error}"));
            resolve_exit_code(&anyhow::Error::from(error))
        }
    }
}

fn run(
    arguments: CommandLineArguments,
    resolver: &dyn SecretResolver,
) -> anyhow::Result<RenderedOutput> {
    let output_format = arguments.global.output;
    let execution = ExecutionContext::from_global_arguments(arguments.global)?;
    match arguments.command {
        TopLevelCommand::Context { command } => {
            let rendered = match command {
                ContextCommand::List => render_output(&list_contexts(&execution)?, output_format)?,
                ContextCommand::Show { name } => {
                    render_output(&show_context(&execution, name.as_deref())?, output_format)?
                }
                ContextCommand::Add(add_arguments) => {
                    render_output(&add_context(&execution, &add_arguments)?, output_format)?
                }
                ContextCommand::Use { name } => {
                    render_output(&use_context(&execution, &name)?, output_format)?
                }
                ContextCommand::Current => {
                    render_output(&show_current_context(&execution)?, output_format)?
                }
                ContextCommand::Test {
                    name,
                    timeout_seconds,
                } => {
                    let timeout = Duration::from_secs(timeout_seconds);
                    render_output(
                        &test_context(&execution, resolver, name.as_deref(), timeout)?,
                        output_format,
                    )?
                }
            };
            Ok(RenderedOutput::complete(rendered))
        }
        TopLevelCommand::Produce(produce_arguments) => {
            produce(&execution, resolver, &TerminalPrompter, &produce_arguments)
        }
        TopLevelCommand::Consume(consume_arguments) => {
            consume(&execution, resolver, &consume_arguments)
        }
        TopLevelCommand::Schema { command } => match command {
            SchemaCommand::Register(register_arguments) => {
                register_schema(&execution, resolver, &TerminalPrompter, &register_arguments)
            }
            SchemaCommand::Get(get_arguments) => get_schema(&execution, resolver, &get_arguments),
            SchemaCommand::CheckCompat(check_arguments) => {
                check_compatibility(&execution, resolver, &check_arguments)
            }
        },
    }
}
